export const getCategoryImage = (categoryName: string): string => {
    // Try exact match
    if (CATEGORY_IMAGES[categoryName]) {
        return CATEGORY_IMAGES[categoryName];
    }

    // Try case-insensitive match
    const lowerName = categoryName.toLowerCase();
    const key = Object.keys(CATEGORY_IMAGES).find(k => k.toLowerCase() === lowerName);
    if (key) {
        return CATEGORY_IMAGES[key];
    }

    // Try partial match for Series names (e.g. "Base" matches "Base Set 2")
    const seriesKey = Object.keys(CATEGORY_IMAGES).find(k => categoryName.startsWith(k));
    if (seriesKey) {
        return CATEGORY_IMAGES[seriesKey];
    }

    return '';
};
